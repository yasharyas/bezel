import type { FrameSpec, InlineGroup, InlineSpec, PreviewSpec, Tone } from "./types";

const inline = (
  group: InlineGroup,
  tone: Tone,
  extra: Omit<InlineSpec, "kind" | "group" | "tone"> = {},
): InlineSpec => ({ kind: "inline", group, tone, ...extra });

const frame = (
  tone: Tone,
  width: number,
  height: number,
  extra: Omit<FrameSpec, "kind" | "tone" | "viewport"> = {},
): FrameSpec => ({ kind: "frame", tone, viewport: { width, height }, ...extra });

